def seedkb(db: Session) -> None:
    # Ensure 'block' column exists in existing database table
    bind = db.get_bind()
    insp = inspect(bind)
    if "kb_articles" in insp.get_table_names():
        columns = [c["name"] for c in insp.get_columns("kb_articles")]
        if "block" not in columns:
            db.execute(text("ALTER TABLE kb_articles ADD COLUMN block VARCHAR(128)"))
            db.commit()

    added = 0
    updated = 0
    for a in seed_articles:
        existing = db.scalar(select(kbarticle).where(kbarticle.question == a["question"]))
        if not existing:
            db.add(kbarticle(**a))
            added += 1
        else:
            changed = False
            for field in ("answer", "category", "block", "tags"):
                if getattr(existing, field, None) != a.get(field):
                    setattr(existing, field, a.get(field))
                    changed = True
            if changed:
                updated += 1
    db.commit()
    print(f"KB seeded: {added} new articles added, {updated} updated (total pool: {len(seed_articles)}).")
